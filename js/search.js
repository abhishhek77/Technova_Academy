/* TechNova Computer Academy - search.js
   Client-side site search. Edit SEARCH_INDEX above to add or change searchable content.
   Each entry: { title, type, url, desc, keywords } */
(function () {
  'use strict';
  var overlay = document.getElementById('searchOverlay');
  if (!overlay) return;
  var input = overlay.querySelector('input'), form = overlay.querySelector('form'),
      list = overlay.querySelector('.search-results'), status = overlay.querySelector('.search-status'),
      closeBtn = overlay.querySelector('.search-close'), lastFocus = null;

  /* Returns index entries where every typed word partially matches; title matches rank higher. */
  function searchSite(query) {
    var tokens = query.toLowerCase().split(/\s+/).filter(Boolean);
    if (!tokens.length) return [];
    return SEARCH_INDEX.map(function (it) {
      var title = it.title.toLowerCase(), hay = (it.title + ' ' + it.type + ' ' + it.desc + ' ' + it.keywords).toLowerCase(), score = 0;
      for (var i = 0; i < tokens.length; i++) {
        if (hay.indexOf(tokens[i]) === -1) return null;
        score += title.indexOf(tokens[i]) !== -1 ? 3 : 1;
        if (title.indexOf(tokens[i]) === 0) score += 1;
      }
      return { it: it, score: score };
    }).filter(Boolean).sort(function (a, b) { return b.score - a.score; }).map(function (x) { return x.it; });
  }

  function el(tag, cls, text) { var e = document.createElement(tag); if (cls) e.className = cls; if (text) e.textContent = text; return e; }

  function render() {
    var q = input.value.trim();
    list.innerHTML = '';
    if (!q) { status.textContent = 'Type a keyword, for example python, admission, trainer or workshop.'; return; }
    var res = searchSite(q);
    if (!res.length) {
      status.textContent = 'No results found for "' + q + '". Try a different or shorter keyword.';
      var s = el('li', 'sugg');
      [['Courses', 'courses.html'], ['Admissions', 'admissions.html'], ['Contact', 'contact.html']].forEach(function (p) {
        var a = el('a', 'btn btn-sm', p[0]); a.href = p[1]; s.appendChild(a);
      });
      list.appendChild(s); return;
    }
    status.textContent = res.length + (res.length === 1 ? ' result' : ' results') + ' for "' + q + '"';
    res.slice(0, 15).forEach(function (r) {
      var li = el('li'), a = el('a'), b = el('b', '', r.title), badge = el('span', 'badge', r.type), d = el('small', '', r.desc);
      a.href = r.url; a.appendChild(b); a.appendChild(badge); a.appendChild(d); li.appendChild(a); list.appendChild(li);
    });
  }

  function openSearch(q) {
    lastFocus = document.activeElement; overlay.hidden = false; document.body.classList.add('no-scroll');
    input.value = q || ''; render(); input.focus();
  }
  function closeSearch() { overlay.hidden = true; document.body.classList.remove('no-scroll'); if (lastFocus && lastFocus.focus) lastFocus.focus(); }

  document.querySelectorAll('.search-toggle').forEach(function (b) { b.addEventListener('click', function () { openSearch(''); }); });
  document.querySelectorAll('form[data-search-form]').forEach(function (f) {
    f.addEventListener('submit', function (e) { e.preventDefault(); openSearch(f.querySelector('input').value); });
  });
  input.addEventListener('input', render);
  form.addEventListener('submit', function (e) { e.preventDefault(); render(); });
  closeBtn.addEventListener('click', closeSearch);
  overlay.addEventListener('click', function (e) { if (e.target === overlay) closeSearch(); });
  list.addEventListener('click', function (e) { if (e.target.closest && e.target.closest('a')) document.body.classList.remove('no-scroll'); });
  document.addEventListener('keydown', function (e) {
    if (e.key === 'Escape' && !overlay.hidden) closeSearch();
    if (e.key === 'Tab' && !overlay.hidden) {
      var f = overlay.querySelectorAll('a[href],button,input'), first = f[0], last = f[f.length - 1];
      if (e.shiftKey && document.activeElement === first) { e.preventDefault(); last.focus(); }
      else if (!e.shiftKey && document.activeElement === last) { e.preventDefault(); first.focus(); }
    }
  });
})();
